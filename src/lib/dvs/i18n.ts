const DICT: Record<UiLang | ReportLang, Record<Key, string>> = { en, he, es };

export function t(
  lang: UiLang | ReportLang,
  key: Key,
  vars?: Record<string, string | number>,
) {
  let s = DICT[lang]?.[key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      s = s.replaceAll(`{${name}}`, String(value));
    }
  }
  return s;
}

